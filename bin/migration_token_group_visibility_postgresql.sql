-- Token group visibility schema-first migration (PostgreSQL 13+).
-- Execute once on the migration owner only, after a fresh backup and object-level GO.
-- This file is intentionally not called by application startup.

CREATE TABLE IF NOT EXISTS token_group_visibilities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "group" varchar(64) NOT NULL,
  visibility varchar(16) NOT NULL,
  start_time bigint NOT NULL DEFAULT 0,
  end_time bigint NOT NULL DEFAULT 0,
  CONSTRAINT uni_token_group_visibilities_group UNIQUE ("group")
);

CREATE INDEX IF NOT EXISTS idx_token_group_visibilities_visibility
  ON token_group_visibilities (visibility);

CREATE TABLE IF NOT EXISTS token_group_visibility_targets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visibility_id integer NOT NULL,
  username varchar(64) NOT NULL,
  CONSTRAINT idx_visibility_username UNIQUE (visibility_id, username),
  CONSTRAINT fk_token_group_visibility_targets_visibility
    FOREIGN KEY (visibility_id) REFERENCES token_group_visibilities (id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_token_group_visibility_targets_visibility_id
  ON token_group_visibility_targets (visibility_id);
